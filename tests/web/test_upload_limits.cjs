const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const source = fs.readFileSync('public/app.js', 'utf8');
const addFiles = source.slice(source.indexOf('function addFiles('), source.indexOf('function render('));
const context = {items: [], MAX_FILE_BYTES:4_490_000, allowed: new Set(['.txt']), suffix:name => name.slice(name.lastIndexOf('.')), crypto, render() {}, message() {}};
vm.createContext(context); vm.runInContext(addFiles, context);
context.addFiles(Array.from({length:100}, (_, i) => ({name:`documento-${i}.txt`, size:100, lastModified:i})));
assert.equal(context.items.length, 100);
assert.ok(context.items.every(item => item.status === 'pending'));
context.addFiles([{name:'limite.txt',size:4_490_000,lastModified:101}, {name:'excesso.txt',size:4_490_001,lastModified:102}]);
assert.equal(context.items[100].status, 'pending');
assert.equal(context.items[101].status, 'invalid');
console.log('Upload: lote de 100 arquivos aceito e limite de tamanho validado.');
